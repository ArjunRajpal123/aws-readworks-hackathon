const GENRE_ES = { Fiction: 'Ficción', Nonfiction: 'No ficción' }

export function addRW(MODES) {
  for (const p of RW) {
    for (const band of ['k2', '35', '68', '912']) {
      for (const es of [false, true]) {
        const base = MODES.find(m => m.id === band + (es ? 'es' : ''))
        const link = `<a href="${p.url}" target="_blank" rel="noopener">readworks.org</a>`
        const note = p.note ? [[es ? 'Nota' : 'Note', p.note]] : []
        MODES.push({
          id: `rw-${p.id}-${band}${es ? 'es' : ''}`, band, rw: p.id, audio: p.id + (es ? 'es' : ''),
          lang: es ? 'es-US' : 'en-US', tab: base.tab, sub: base.sub, voice: base.voice, reward: base.reward, stopTitle: base.stopTitle, how: base.how,
          title: p.title,
          details: es
            ? [['Grado', p.grade], ['Género', GENRE_ES[p.genre] || p.genre], ['Fuente', link], ['Texto', 'Traducción automática (borrador de Claude), no es texto de ReadWorks. Pendiente de revisión.'], ...note]
            : [['Grade', p.grade], ['Genre', p.genre], ['Source', link], ['Text', 'Sentences copied from the ReadWorks passage; check against the source before classroom use.'], ...note],
          paras: es ? p.es : p.en,
          stops: [],
        })
      }
    }
  }
}
